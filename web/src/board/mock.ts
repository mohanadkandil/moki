// Used only with ?mock=board, to work on the studio without the job API. Nothing here was rendered:
// the studio labels it. &scenario= picks a state to look at: clean | drc | failed | skipped.
import { STAGE_ORDER } from './logic';
import type { Artifact, ArtifactKind, BoardApi, BoardJob, JobStage } from './types';

const MS: Record<string, number> = { codegen: 4, render: 1400, route: 1900, svg: 49, gltf: 310, fab: 62, enclosure: 840, firmware: 12, 'firmware-compile': 900 };
/** Mock stages play back faster than their stated times. */
const SPEED = 3;

const SVG_SCHEMATIC = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="500"><rect class="boundary" width="800" height="500" fill="#f5f1ed"/><rect x="300" y="150" width="200" height="200" fill="#ffffc2" stroke="#840000"/><path d="M500 200h140M160 300h140" stroke="#009600" fill="none"/><text x="400" y="255" text-anchor="middle" font-family="sans-serif" font-size="22">MOCK SCHEMATIC</text></svg>`;
const SVG_PCB = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600"><rect class="boundary" width="800" height="600" fill="#000" data-type="pcb_background" data-pcb-layer="global"/><rect x="100" y="60" width="600" height="480" fill="none" stroke="#fff" data-pcb-layer="board"/><path d="M180 180H620" stroke="#c84c4c" stroke-width="6" data-pcb-layer="top"/><path d="M180 420H620" stroke="#4d7fc4" stroke-width="6" data-pcb-layer="bottom"/><text x="400" y="310" fill="#fff" text-anchor="middle" font-family="sans-serif" font-size="22" data-pcb-layer="global">MOCK PCB</text></svg>`;
const TSX = `// MOCK SOURCE: not generated by the pipeline.\nexport default () => (\n  <board width="80mm" height="70mm">\n    <chip name="U1" footprint="dip38_w25.4mm" />\n  </board>\n)\n`;
const STL = `solid mock\nfacet normal 0 0 1\nouter loop\nvertex 0 0 0\nvertex 80 0 0\nvertex 0 70 0\nendloop\nendfacet\nendsolid mock\n`;
const ENCLOSURE = { outer: { x: 86, y: 76, z: 34 }, wall: 2, clearance: 0.3, apertures: [{ face: 'front', part: 'USB (mock)', x: 12, y: 4, w: 12, h: 8 }], assumptions: ['Mock data.'] };
const BUILD = { compiled: true, board: 'esp32dev', platform: 'mock', flash: { percent: 23.8, usedBytes: 312_000, totalBytes: 1_310_720 }, ram: { percent: 6.7, usedBytes: 22_000, totalBytes: 327_680 }, logTail: 'MOCK build log', physicalFlash: false };

function blobUrl(content: BlobPart, type: string) { return URL.createObjectURL(new Blob([content], { type })); }

function art(url: string, kind: ArtifactKind, bytes: number): Artifact { return { url, kind, bytes, sha256: '0'.repeat(64) }; }

function textArt(text: string, type: string, kind: ArtifactKind): Artifact { return art(blobUrl(text, type), kind, text.length); }

async function glb(width: number, depth: number, height: number): Promise<ArrayBuffer> {
  const THREE = await import('three');
  const { GLTFExporter } = await import('three/addons/exporters/GLTFExporter.js');
  const mesh = new THREE.Mesh(new THREE.BoxGeometry(width, height, depth), new THREE.MeshStandardMaterial({ color: '#1f5a3c' }));
  return (await new GLTFExporter().parseAsync(mesh, { binary: true })) as ArrayBuffer;
}

/** A stored (uncompressed) ZIP with zeroed checksums. Enough for the viewer; it is a mock. */
function storedZip(files: Record<string, string>): Uint8Array {
  const enc = new TextEncoder();
  const chunks: Uint8Array[] = [];
  const central: Uint8Array[] = [];
  let offset = 0;
  for (const [path, text] of Object.entries(files)) {
    const name = enc.encode(path);
    const data = enc.encode(text);
    const local = new DataView(new ArrayBuffer(30));
    local.setUint32(0, 0x04034b50, true); local.setUint32(18, data.length, true); local.setUint32(22, data.length, true); local.setUint16(26, name.length, true);
    const dir = new DataView(new ArrayBuffer(46));
    dir.setUint32(0, 0x02014b50, true); dir.setUint32(20, data.length, true); dir.setUint32(24, data.length, true); dir.setUint16(28, name.length, true); dir.setUint32(42, offset, true);
    chunks.push(new Uint8Array(local.buffer), name, data);
    central.push(new Uint8Array(dir.buffer), name);
    offset += 30 + name.length + data.length;
  }
  const dirSize = central.reduce((a, c) => a + c.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true); end.setUint16(8, Object.keys(files).length, true); end.setUint16(10, Object.keys(files).length, true); end.setUint32(12, dirSize, true); end.setUint32(16, offset, true);
  const parts = [...chunks, ...central, new Uint8Array(end.buffer)];
  const out = new Uint8Array(parts.reduce((a, p) => a + p.length, 0));
  let at = 0;
  for (const p of parts) { out.set(p, at); at += p.length; }
  return out;
}

export function createMockApi(scenario: string): BoardApi {
  const jobs = new Map<string, { startedAt: number; template?: string; source: boolean }>();
  let artifacts: Promise<Record<string, Artifact>> | null = null;
  const makeArtifacts = () => (artifacts ??= (async () => {
    const zip = storedZip({ 'platformio.ini': '; MOCK\n[env:esp32dev]\nboard = esp32dev\n', 'include/pins.h': '// MOCK\n#define PIN_OLED_SDA 21\n#define PIN_OLED_SCL 22\n', 'src/main.cpp': '// MOCK\n#include "pins.h"\nvoid setup() {}\nvoid loop() {}\n' });
    const [board, assembly] = await Promise.all([glb(80, 70, 1.6), glb(86, 76, 34)]);
    return {
      'board.tsx': textArt(TSX, 'text/plain', 'source'),
      'circuit.json': textArt('[]', 'application/json', 'json'),
      'schematic.svg': textArt(SVG_SCHEMATIC, 'image/svg+xml', 'svg'),
      'pcb.svg': textArt(SVG_PCB, 'image/svg+xml', 'svg'),
      'board.glb': art(blobUrl(board, 'model/gltf-binary'), 'glb', board.byteLength),
      'assembly.glb': art(blobUrl(assembly, 'model/gltf-binary'), 'glb', assembly.byteLength),
      'enclosure-base.stl': textArt(STL, 'model/stl', 'stl'),
      'enclosure-lid.stl': textArt(STL, 'model/stl', 'stl'),
      'enclosure.step': textArt('ISO-10303-21;\n/* MOCK */\nEND-ISO-10303-21;\n', 'model/step', 'step'),
      'enclosure.json': textArt(JSON.stringify(ENCLOSURE), 'application/json', 'json'),
      'firmware.zip': art(blobUrl(zip.slice().buffer, 'application/zip'), 'zip', zip.length),
      'firmware-build.json': textArt(JSON.stringify(BUILD), 'application/json', 'json'),
      'gerbers.zip': art(blobUrl(zip.slice().buffer, 'application/zip'), 'zip', zip.length),
      'bom.csv': textArt('ref,part\nU1,MOCK\n', 'text/csv', 'csv'),
      'pnp.csv': textArt('ref,x,y\nU1,0,0\n', 'text/csv', 'csv'),
      'receipt.json': textArt('{"mock":true}', 'application/json', 'json'),
    };
  })());

  return {
    isMock: true,
    async create(body) {
      const jobId = `mock-${jobs.size + 1}`;
      jobs.set(jobId, { startedAt: Date.now(), template: 'design' in body ? body.design.template : undefined, source: 'source' in body });
      return { jobId };
    },
    async get(jobId) {
      const entry = jobs.get(jobId);
      if (!entry) throw new Error(`Mock job ${jobId} is gone. Mock jobs live only in this tab.`);
      const failAt = scenario === 'failed' ? 'route' : null;
      const stages: JobStage[] = [];
      let at = 0;
      let done = true;
      for (const name of STAGE_ORDER) {
        at += MS[name]! / SPEED;
        if (Date.now() - entry.startedAt < at) { done = false; break; }
        if (name === failAt) { stages.push({ name, status: 'failed', ms: MS[name]!, note: 'Mock failure: the autorouter gave up.' }); break; }
        const skipped = (name === 'firmware' || name === 'firmware-compile') && (entry.source || scenario === 'skipped');
        stages.push(skipped
          ? { name, status: 'skipped', ms: 0, note: entry.source ? 'Edited source has no design to generate firmware from.' : 'Mock: PlatformIO is not installed.' }
          : { name, status: 'done', ms: MS[name]! });
      }
      const failed = stages.some(s => s.status === 'failed');
      const job: BoardJob = {
        jobId,
        status: failed ? 'failed' : done ? 'done' : 'running',
        input: { kind: entry.source ? 'source' : 'design', template: entry.template },
        cache: 'miss',
        stages,
      };
      if (failed) job.error = 'Mock failure: the render process exited at the route stage.';
      if (job.status === 'done') {
        const all = await makeArtifacts();
        job.artifacts = scenario === 'skipped' || entry.source ? Object.fromEntries(Object.entries(all).filter(([k]) => !k.startsWith('firmware'))) : all;
        job.totalMs = stages.reduce((a, s) => a + s.ms, 0) + 140;
        job.board = { widthMm: 80, heightMm: 70, layers: 2, traceCount: 13, viaCount: 0 };
        job.drc = scenario === 'drc'
          ? { errors: [{ type: 'pcb_component_outside_board_error', message: 'Mock: U1 extends 2.1 mm past the board edge.' }], warnings: [{ type: 'pcb_trace_warning', message: 'Mock: a warning.' }] }
          : { errors: [], warnings: [] };
        job.toolVersions = { tscircuit: 'mock' };
      }
      return job;
    },
  };
}
