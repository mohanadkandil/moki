// enclosure.json (schema moki.enclosure/1) belongs to the enclosure generator, so every read is guarded:
// a field that's missing or renamed drops its row. It can't crash the tab or print "undefined".
type Json = Record<string, unknown>;
const isObject = (v: unknown): v is Json => typeof v === 'object' && v !== null && !Array.isArray(v);
const obj = (v: unknown): Json => (isObject(v) ? v : {});
const objects = (v: unknown): Json[] => (Array.isArray(v) ? v.filter(isObject) : []);
const str = (v: unknown): string | null => (typeof v === 'string' && v ? v : null);
const num = (v: unknown): number | null => (typeof v === 'number' && Number.isFinite(v) ? v : null);
const mm = (v: unknown): string | null => { const n = num(v); return n === null ? null : `${+n.toFixed(2)} mm`; };
const box = (v: unknown): string | null => {
  const { x, y, z } = obj(v);
  const [a, b, c] = [num(x), num(y), num(z)];
  return a === null || b === null || c === null ? null : `${+a.toFixed(1)} × ${+b.toFixed(1)} × ${+c.toFixed(1)} mm`;
};

const FACES: Record<string, string> = { x_neg: 'left wall', x_pos: 'right wall', y_neg: 'front wall', y_pos: 'back wall', z_pos: 'top', z_neg: 'floor' };
const PURPOSES: Record<string, string> = { usb: 'USB cable', vent: 'Vent slots', sound: 'Sound holes', 'encoder-shaft': 'Encoder shaft', 'display-active-area': 'Display window' };

function Rows({ rows }: { rows: readonly (readonly [string, string | null])[] }) {
  const shown = rows.filter((r): r is readonly [string, string] => r[1] !== null);
  if (!shown.length) return null;
  return <dl className="lab-behavior bs-rows">{shown.map(([k, v]) => <div key={k}><dt>{k}</dt><dd>{v}</dd></div>)}</dl>;
}

function Aperture({ a }: { a: Json }) {
  const purpose = str(a.purpose);
  const size = obj(a.sizeMm);
  const w = num(size.width);
  const h = num(size.height);
  const count = num(a.count);
  const where = [str(a.onPart), FACES[str(a.face) ?? ''] ?? str(a.face)].filter(Boolean).join(', ');
  const measure = [w !== null && h !== null ? `${+w.toFixed(1)} × ${+h.toFixed(1)} mm` : null, count !== null ? `${count} of them` : null].filter(Boolean).join(', ');
  const part = str(a.part);
  return (
    <li>
      <span className="bs-aperture-head">
        <strong>{(purpose && PURPOSES[purpose]) ?? purpose ?? str(a.id) ?? 'Opening'}</strong>
        {part && part !== 'enclosure' && <span className="lab-ref lab-mono">{part}</span>}
        {measure && <span className="bs-aperture-size">{measure}</span>}
      </span>
      {where && <span className="lab-quiet">{where}</span>}
      {str(a.note) && <span className="bs-aperture-note">{str(a.note)}</span>}
    </li>
  );
}

function shellCheck(v: unknown): string | null {
  const shell = obj(v);
  const stl = obj(shell.stl);
  if (typeof stl.watertight !== 'boolean') return null;
  const bad = num(stl.nonManifoldEdges);
  const solid = shell.isValid === false ? ', invalid solid' : '';
  return `${stl.watertight ? 'Watertight' : 'Not watertight'}${bad !== null ? `, ${bad} non-manifold edges` : ''}${solid}`;
}

