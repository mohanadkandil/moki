import { createRequire } from 'node:module';
const require = createRequire('/home/sogo/.local/share/sogo-diagrams/');
const puppeteer = require('puppeteer-core');
const [out, url] = process.argv.slice(2);
process.env.LD_LIBRARY_PATH = '/home/sogo/.local/share/sogo-diagrams/lib';
const b = await puppeteer.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux-arm64/chrome-headless-shell', headless: 'shell', args: ['--no-sandbox', '--use-angle=swiftshader', '--use-gl=angle', '--enable-webgl', '--ignore-gpu-blocklist', '--enable-unsafe-swiftshader'], defaultViewport: { width: 1440, height: 900 } });
const p = await b.newPage();
const t0 = Date.now(); const ev = [];
const glb = r => /\.(glb|stl)$/.test(r.url());
const name = r => r.url().split('/').pop();
p.on('request', r => { if (glb(r)) ev.push([Date.now() - t0, 'start', name(r)]); });
p.on('requestfinished', r => { if (glb(r)) ev.push([Date.now() - t0, 'finished', name(r)]); });
p.on('requestfailed', r => { if (glb(r)) ev.push([Date.now() - t0, 'failed', name(r), r.failure()?.errorText]); });
await p.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
await p.goto(url + '&tab=3d', { waitUntil: 'load' });
const sleep = ms => new Promise(r => setTimeout(r, ms));
const ready = () => p.waitForFunction(() => document.querySelector('.bs-model')?.dataset.status === 'ready', { timeout: 90000 });
await p.waitForSelector('.bs-model'); await ready();
await p.click('.bs-switch'); await sleep(300); await ready();
await p.click('.bs-switch'); await sleep(300); await ready();
await sleep(1000);
const spin = await p.evaluate(() => { const s = document.createElement('div'); s.className = 'bs-spin'; document.querySelector('.lab').append(s); const a = getComputedStyle(s).animationName; s.remove(); return a; });
const result = { reducedMotionSpinnerAnimation: spin, requests: ev };
console.log(JSON.stringify(result, null, 1));
(await import('node:fs')).writeFileSync(out, JSON.stringify(result, null, 2));
await b.close();
