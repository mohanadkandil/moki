function DrcEntries({ entries, tone }: { entries: DrcEntry[]; tone: 'error' | 'warn' }) {
  return <ul>{entries.map((e, i) => <li key={i} className={`is-${tone}`}><span className="lab-mono">{e.type}</span> {e.message}</li>)}</ul>;
}

/** Errors are always open. Warnings fold away when there are many, with their count still in view. */
export function DrcList({ job, compact }: { job: BoardJob; compact?: boolean }) {
  const errors: DrcEntry[] = job.drc?.errors ?? [];
  const warnings: DrcEntry[] = job.drc?.warnings ?? [];
  if (!drcRan(job)) return compact ? null : <p className="lab-quiet">The design rule check hasn’t run for this build.</p>;
  if (!errors.length && !warnings.length) return <p className="bs-drc-clean"><CircleCheck size={14} aria-hidden="true" />DRC: 0 errors, 0 warnings</p>;
  const summary = `DRC: ${errors.length} error${errors.length === 1 ? '' : 's'}, ${warnings.length} warning${warnings.length === 1 ? '' : 's'}`;
  return (
    <div className={`bs-drc ${errors.length ? 'is-error' : 'is-warn'} ${compact ? 'is-compact' : ''}`} role={errors.length ? 'alert' : undefined}>
      {errors.length > 0 && <p className="bs-drc-head"><CircleAlert size={14} aria-hidden="true" />{summary}</p>}
      {errors.length > 0 && <DrcEntries entries={errors} tone="error" />}
      {warnings.length > 0 && (
        <details open={warnings.length <= 3 && !compact}>
          <summary>{errors.length ? `${warnings.length} warning${warnings.length === 1 ? '' : 's'}` : summary}</summary>
          <DrcEntries entries={warnings} tone="warn" />
        </details>
      )}
    </div>
  );
}

export interface CodeDraft { text: string; base: string | null; baseJobId: string | null }

export function CodePanel({ job, draft, setDraft, busy, onRender, olderBuild }: {
  job: BoardJob; draft: CodeDraft; setDraft: (d: CodeDraft) => void; busy: boolean; onRender: () => void; olderBuild: boolean;
}) {
  const artifact = job.artifacts?.['board.tsx'];
  const source = useArtifact(artifact, asText);
  const gutter = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (source.state !== 'ready') return;
    // A new build replaces the text only when there are no unsaved edits. Edits are never overwritten.
    if (draft.base === null || draft.text === draft.base) setDraft({ text: source.value, base: source.value, baseJobId: job.jobId });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [source.state === 'ready' ? source.value : null, job.jobId]);
  if (!artifact && draft.base === null) return <Absent noun="source" job={job} stage="codegen" />;
  if (draft.base === null) return <Fetching what="board.tsx" error={source.state === 'error' ? source.message : undefined} />;
  const dirty = draft.text !== draft.base;
  const lineCount = draft.text.split('\n').length;
  return (
    <div className="bs-split is-code">
      <div className="bs-split-view">
        <div className="bs-panel-tools">
          <button type="button" className="lab-primary" disabled={busy || !dirty} onClick={onRender}>{busy ? 'Rendering…' : 'Re-render'}</button>
          <button type="button" className="lab-text-button" disabled={!dirty} onClick={() => setDraft({ ...draft, text: draft.base ?? '' })}><RotateCcw size={14} aria-hidden="true" />Discard edits</button>
          <span className="lab-quiet">{dirty ? 'Edited. Ctrl or ⌘ + Enter re-renders.' : 'Edit the TSX to re-render it.'}</span>
        </div>
        <div className="bs-editor">
          <div className="bs-gutter" ref={gutter} aria-hidden="true">{Array.from({ length: lineCount }, (_, i) => <span key={i}>{i + 1}</span>)}</div>
          <textarea
            aria-label="Board source, board.tsx"
            spellCheck={false}
            autoCapitalize="off"
            autoCorrect="off"
            wrap="off"
            value={draft.text}
            onChange={e => setDraft({ ...draft, text: e.target.value })}
            onScroll={e => { if (gutter.current) gutter.current.scrollTop = e.currentTarget.scrollTop; }}
            onKeyDown={e => { if (e.key === 'Enter' && (e.ctrlKey || e.metaKey) && dirty && !busy) { e.preventDefault(); onRender(); } }}
          />
        </div>
      </div>
      <div className="bs-split-side">
        <section className="lab-section" aria-labelledby="code-drc">
          <h2 id="code-drc">{olderBuild ? 'Design rule check, last finished build' : 'Design rule check'}</h2>
          <DrcList job={job} />
          <p className="lab-quiet">DRC checks board geometry: clearances, outlines and routing. It doesn’t show the circuit works.</p>
        </section>
        <p className="lab-note is-info">Your edit runs in a separate process on this machine, stopped after 120 s. Edited source has no design graph, so firmware is skipped.</p>
      </div>
    </div>
  );
}

const FILE_GROUPS: readonly { title: string; names: readonly [string, string][] }[] = [
  { title: 'Source', names: [['board.tsx', 'tscircuit source, editable in Code'], ['circuit.json', 'Everything tscircuit computed']] },
  { title: 'Drawings and 3D', names: [['schematic.svg', 'Schematic'], ['pcb.svg', 'PCB layout'], ['board.glb', 'Populated board']] },
  { title: 'Fabrication', names: [['gerbers.zip', 'Gerbers for a board house'], ['bom.csv', 'Bill of materials'], ['pnp.csv', 'Pick and place'], ['kicad.zip', 'Open in KiCad']] },
  { title: 'Enclosure', names: [['enclosure-base.stl', 'Base, for printing'], ['enclosure-lid.stl', 'Lid, for printing'], ['enclosure.step', 'Editable solid for CAD'], ['assembly.glb', 'Board inside the enclosure'], ['enclosure.json', 'Dimensions and openings']] },
  { title: 'Firmware', names: [['firmware.zip', 'PlatformIO project'], ['firmware-build.json', 'Compile receipt']] },
  { title: 'Receipt', names: [['receipt.json', 'Timings, DRC and tool versions']] },
];

export function FilesPanel({ job }: { job: BoardJob }) {
  const artifacts = job.artifacts ?? {};
  const known = new Set(FILE_GROUPS.flatMap(g => g.names.map(([n]) => n)));
  const extra = Object.keys(artifacts).filter(n => !known.has(n));
  const groups = extra.length ? [...FILE_GROUPS, { title: 'Other', names: extra.map(n => [n, ''] as [string, string]) }] : FILE_GROUPS;
  const versions = Object.entries(job.toolVersions ?? {});
  return (
    <div className="bs-files">
      <div className="bs-file-groups">
        {groups.map(group => (
          <section key={group.title} className="lab-section">
            <h2>{group.title}</h2>
            <ul className="bs-file-list">
              {group.names.map(([name, what]) => {
                const a = artifacts[name];
                return (
                  <li key={name} className={a ? '' : 'is-missing'}>
                    <span className="bs-file-name"><span className="lab-mono">{name}</span><span className="lab-quiet">{what}</span></span>
                    {a ? (
                      <>
                        <span className="bs-file-hash lab-mono" title={`sha256 ${a.sha256}`}>{a.sha256.slice(0, 8)}</span>
                        <span className="bs-file-size">{formatBytes(a.bytes)}</span>
                        <a className="bs-file-get" href={a.url} download={name} aria-label={`Download ${name}`}><Download size={15} aria-hidden="true" /></a>
                      </>
                    ) : <span className="bs-file-none">not produced</span>}
                  </li>
                );
              })}
            </ul>
          </section>
        ))}
      </div>
      <aside className="bs-file-side">
        <section className="lab-section" aria-labelledby="versions-heading">
          <h2 id="versions-heading">Tool versions, as run</h2>
          {versions.length ? (
            <dl className="lab-behavior bs-rows">{versions.map(([k, v]) => <div key={k}><dt className="lab-mono">{k}</dt><dd className="lab-mono" title={v}>{/^[0-9a-f]{32,}$/i.test(v) ? `${v.slice(0, 12)}…` : v}</dd></div>)}</dl>
          ) : <p className="lab-quiet">This build reported no tool versions.</p>}
        </section>
        <p className="lab-quiet">Job <span className="lab-mono">{job.jobId}</span></p>
      </aside>
    </div>
  );
}
