/** Why an output is absent, in the pipeline's own words when it gave any. */
function absentReason(job: BoardJob, stageName: string): string {
  const stage: JobStage | undefined = job.stages?.find(s => s.name === stageName);
  if (stage?.status === 'skipped') return `The ${stageName} stage was skipped: ${stage.note ?? 'no reason given'}`;
  if (stage?.status === 'failed') return `The ${stageName} stage failed: ${stage.note ?? 'no reason given'}`;
  if (job.status === 'queued' || job.status === 'running') return `It appears when the ${stageName} stage finishes.`;
  if (job.status === 'failed') return (job.error && firstErrorLine(job.error)) || 'The build failed before this stage.';
  return `This build produced no output for the ${stageName} stage.`;
}

export function Absent({ noun, job, stage }: { noun: string; job: BoardJob; stage: string }) {
  const busy = job.status === 'queued' || job.status === 'running';
  const title = busy ? `No ${noun} yet` : `No ${noun} in this build`;
  return (
    <div className="bs-state">
      {busy ? <LoaderCircle size={20} className="bs-spin" aria-hidden="true" /> : <CircleAlert size={20} aria-hidden="true" />}
      <p><strong>{title}</strong></p>
      <p className="lab-quiet">{absentReason(job, stage)}</p>
    </div>
  );
}

function Fetching({ what, error }: { what: string; error?: string }) {
  return error
    ? <div className="bs-state" role="alert"><CircleAlert size={20} aria-hidden="true" /><p><strong>{what} didn’t load.</strong></p><p className="lab-quiet">{error}</p></div>
    : <div className="bs-state" role="status"><LoaderCircle size={20} className="bs-spin" aria-hidden="true" /><p>Loading {what}…</p></div>;
}

function FileLink({ name, artifact, children }: { name: string; artifact: Artifact; children?: ReactNode }) {
  return <a className="bs-download" href={artifact.url} download={name}><Download size={14} aria-hidden="true" />{children ?? name}<span className="bs-download-size">{formatBytes(artifact.bytes)}</span></a>;
}

